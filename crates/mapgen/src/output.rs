//! map.json (the core's format, plus `geo`) and hillshade.json.

use serde_json::{json, Value};

use crate::geo::{BBox, Grid};

/// Inputs of a generated map.
pub struct MapInput<'a> {
    pub grid: &'a Grid,
    /// Terrain id per [row][col].
    pub terrain: &'a [Vec<String>],
    pub pass: &'a [Vec<bool>],
    pub legend: &'a [(String, char)],
    pub pass_char: char,
    pub bbox: BBox,
    pub hex_km: f64,
    pub sources: &'a [String],
    pub roads: &'a [[[i32; 2]; 2]],
    pub canals: &'a [[[i32; 2]; 2]],
    pub bridges: &'a [[[i32; 2]; 2]],
    pub places: &'a [Value],
}

/// Builds map.json rows from terrain ids; control is left to the editor.
pub fn map_json(m: &MapInput<'_>) -> Result<Value, String> {
    let MapInput {
        grid,
        terrain,
        pass,
        legend,
        pass_char,
        bbox,
        hex_km,
        sources,
        roads,
        canals,
        bridges,
        places,
    } = *m;
    let ch = |t: &str| {
        legend
            .iter()
            .find(|(id, _)| id == t)
            .map(|(_, c)| *c)
            .ok_or_else(|| format!("no legend character for `{t}`"))
    };
    let mut rows = Vec::new();
    for row in 0..grid.rows as usize {
        let mut line = String::new();
        for col in 0..grid.cols as usize {
            let t = &terrain[row][col];
            line.push(if pass[row][col] { pass_char } else { ch(t)? });
        }
        rows.push(Value::String(line));
    }
    let mut legend_json = serde_json::Map::new();
    for (id, c) in legend {
        legend_json.insert(c.to_string(), json!({ "terrain": id }));
    }
    if let Some((mountains, _)) = legend.iter().find(|(id, _)| id == "mountains") {
        legend_json.insert(
            pass_char.to_string(),
            json!({ "terrain": mountains, "pass": true }),
        );
    }
    let control = vec![Value::String(".".repeat(grid.cols as usize)); grid.rows as usize];
    Ok(json!({
        "_comment": "Generated by mapgen from DEM/OSM; edit in the map editor. Data: see LICENSE-DATA.md.",
        "width": grid.cols,
        "height": grid.rows,
        "legend": legend_json,
        "terrain": rows,
        "control_legend": {},
        "control": control,
        "roads": roads,
        "canals": canals,
        "bridges": bridges,
        "geo": {
            "bbox": [bbox.west, bbox.south, bbox.east, bbox.north],
            "hex_km": hex_km,
            "hillshade": "hillshade.png",
            "sources": sources,
            "places": places,
        }
    }))
}

/// Where the hillshade image lies relative to the centre of hex (0, 0):
/// its top-left corner is at (−R, −√3·R/2) km.
pub fn hillshade_json(grid: &Grid, width_px: u32, height_px: u32, px_per_km: f64) -> Value {
    let r = grid.radius_km;
    json!({
        "png": "hillshade.png",
        "width_px": width_px,
        "height_px": height_px,
        "px_per_km": px_per_km,
        "hex_radius_km": r,
        "top_left_from_hex00_km": [-r, -r * 3f64.sqrt() / 2.0],
    })
}
